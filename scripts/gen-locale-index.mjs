#!/usr/bin/env node
// ============================================================
// gen-locale-index.mjs — regenerates packages/core/locales/index.js.
//
//   node scripts/gen-locale-index.mjs
//
// The lazy catalog map used to be Vite-only (`import.meta.glob`), which Metro
// (the Expo bundler, Phase 1) cannot evaluate. This emits a STATIC map of
// dynamic imports — every bundler can code-split those — generated from the
// catalog directories that actually exist on disk. Output is committed;
// re-run after adding a language catalog (e.g. via scripts/i18n-translate.mjs).
// ============================================================
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const LOC = path.join(ROOT, 'packages/core/locales')

const codes = fs.readdirSync(LOC, { withFileTypes: true })
  .filter((d) => d.isDirectory() && fs.existsSync(path.join(LOC, d.name, 'common.json')))
  .map((d) => d.name)
  .sort()

const out = `// AUTO-GENERATED by scripts/gen-locale-index.mjs — do not edit by hand.
// Static lazy-loader map over the catalog dirs on disk. Replaces Vite-only
// import.meta.glob so Metro (Expo) can bundle the same catalogs in Phase 1.
// Languages in the registry without a generated catalog fall back to English
// at the call site, exactly as the glob (which only matched real files) did.
export const CATALOGS = {
${codes.map((c) => `  ${c}: () => import('./${c}/common.json'),`).join('\n')}
}
`

fs.writeFileSync(path.join(LOC, 'index.js'), out)
console.log(`packages/core/locales/index.js — ${codes.length} catalogs: ${codes.join(', ')}`)
